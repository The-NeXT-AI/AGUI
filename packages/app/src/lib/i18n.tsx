function normalizeLang(value: unknown): Lang | undefined {
  const language = String(value ?? "").toLowerCase();
  if (language === "zh" || language.startsWith("zh-")) return "zh";
  if (language === "en" || language.startsWith("en-")) return "en";
  return undefined;
}

function initialLang(): Lang {
  return normalizeLang(globalThis.navigator?.language) ?? productConfig.defaults.language;
}

function applyLangToDocument(lang: Lang): void {
  globalThis.document?.documentElement.setAttribute("lang", lang === "zh" ? "zh-CN" : "en");
}

function currentLang(): Lang {
  return normalizeLang(i18next.resolvedLanguage || i18next.language) ?? initialLang();
}

function setLang(lang: Lang): void {
  void i18next.changeLanguage(lang);
}

function toggleLang(): void {
  setLang(currentLang() === "en" ? "zh" : "en");
}

function productTranslations(lang: Lang): Record<string, string> {
  return {
    ...translations[lang],
    "app.title": productConfig.app.name,
    ...productConfig.ui.text,
    ...productConfig.ui.translations[lang],
  };
}

void i18next.use(initReactI18next).init({
  fallbackLng: productConfig.defaults.language,
  interpolation: {
    escapeValue: false,
  },
  lng: initialLang(),
  resources: {
    en: { translation: productTranslations("en") },
    zh: { translation: productTranslations("zh") },
  },
});

i18next.on("languageChanged", (language) => {
  const lang = normalizeLang(language) ?? "en";
  applyLangToDocument(lang);
  void persistLang(lang);
});

subscribeProductConfig(() => {
  i18next.addResourceBundle("en", "translation", productTranslations("en"), true, true);
  i18next.addResourceBundle("zh", "translation", productTranslations("zh"), true, true);
  void i18next.changeLanguage(currentLang());
});

applyLangToDocument(currentLang());
void hydrateStoredLang();

async function hydrateStoredLang(): Promise<void> {
  const { readPersistentValue } = await import("@/storage/persistent-storage");
  const stored = normalizeLang(await readPersistentValue(LANGUAGE_STORAGE_KEY));
  if (stored && stored !== currentLang()) await i18next.changeLanguage(stored);
}

async function persistLang(lang: Lang): Promise<void> {
  const { writePersistentValue } = await import("@/storage/persistent-storage");
  await writePersistentValue(LANGUAGE_STORAGE_KEY, lang);
}

export function useI18nStore<T>(selector: (state: I18nStore) => T): T {
  const { i18n } = useTranslation();
  const lang =
    normalizeLang(i18n.resolvedLanguage || i18n.language) ?? productConfig.defaults.language;
  return selector({
    lang,
    setLang,
    toggleLang,
  });
}

export type TranslateFn = (key: string, options?: TOptions) => string;

export function t(key: string, options?: TOptions): string {
  return i18next.t(key, options);
}

export function useT(): TranslateFn {
  const { t: translate } = useTranslation();
  return useCallback((key, options) => translate(key, options), [translate]);
}
